package com.glyphsense.app.glyph

object AppGlyphs {

    fun glyphFor(packageName: String, side: Int): IntArray? {
        val canonical = Aliases[packageName] ?: packageName
        return Patterns[canonical to side]
    }

    private val Aliases: Map<String, String> = mapOf(
        "com.whatsapp.w4b" to "com.whatsapp",
        "com.samsung.android.messaging" to "com.google.android.apps.messaging"
    )

    private fun compile(side: Int, rows: Array<out String>): IntArray {
        val frame = IntArray(side * side)
        for (y in 0 until side) {
            val row = if (y < rows.size) rows[y] else ""
            for (x in 0 until side) {
                val c = if (x < row.length) row[x] else '.'
                frame[y * side + x] = when (c) {
                    '#', 'X' -> 255
                    '+' -> 200
                    '-' -> 130
                    ':' -> 70
                    else -> 0
                }
            }
        }
        return frame
    }

    private fun p25(vararg rows: String): IntArray = compile(25, rows)
    private fun p13(vararg rows: String): IntArray = compile(13, rows)

